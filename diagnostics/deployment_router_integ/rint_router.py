"""ROUTER-INTEG: adapter of the frozen lightweight router, and the exact model-identifier mapping.

The router is the one of the router study, unchanged: five cross-validation fold models (router/router_heads.npz,
regenerated by the original training code and verified against the stored per-query scores; see
router/router_build_report.json). A query of the pool is scored by the fold model that did not see it in training
(router/fold_map.json). Raw query text goes through

    all-MiniLM-L6-v2 WordPiece tokenizer (truncation at 256 tokens) -> encoder (no pooler)
      -> attention-mask mean pooling -> L2 normalisation -> MLP head (384 -> 64 ReLU -> 1) -> score
    score > 0 -> Qwen3-8B, otherwise DeepSeek-R1-0528-Qwen3-8B

which is the path the router study timed (time_minilm_end_to_end.py). The threshold is the study's and is not tuned.
The router chooses between its two original models only. Its output is never mapped to any other model.

Needs numpy, torch and transformers. No scikit-learn: the heads are plain arrays.
"""
import hashlib
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rint_common as C  # noqa: E402
import rint_spec as S  # noqa: E402

ROUTER_DIR = C.RI_DIR / "router"


def choice_of(score):
    """Exact mapping from a router score to a model key of rint_spec.MODELS."""
    return S.ROUTER_CLASS_TO_MODEL[int(float(score) > S.ROUTER_THRESHOLD)]


def canonical_heads_sha256(arrays):
    h = hashlib.sha256()
    for name in sorted(arrays):
        h.update(name.encode() + b"\0" + str(arrays[name].shape).encode() + b"\0" + np.ascontiguousarray(arrays[name]).tobytes())
    return h.hexdigest()


class Heads:
    """The five fold heads. score(fold, emb) is the plain forward pass in the weights' own precision."""

    def __init__(self, path=None, check=True):
        z = np.load(path or ROUTER_DIR / "router_heads.npz")
        self.arrays = {k: z[k] for k in z.files}
        self.sha256 = canonical_heads_sha256(self.arrays)
        if check:
            rep = C.read_json(ROUTER_DIR / "router_build_report.json")
            if rep["heads_canonical_sha256"] != self.sha256 or rep["problems"]:
                raise C.Stop("router heads are not the verified export")
        for f in range(S.ROUTER_FOLDS):
            n = sum(self.arrays[f"fold{f}_{k}"].size for k in ("W1", "b1", "W2", "b2"))
            if n != S.ROUTER_HEAD_PARAMS:
                raise C.Stop(f"fold {f} head has {n} parameters")

    def score(self, fold, emb):
        a = self.arrays
        W1, b1, W2, b2 = (a[f"fold{int(fold)}_{k}"] for k in ("W1", "b1", "W2", "b2"))
        x = np.asarray(emb, dtype=W1.dtype).reshape(-1, W1.shape[0])
        return (np.maximum(x @ W1 + b1, 0.0) @ W2 + b2).ravel()


class FoldMap:
    """Which fold model scores a pool query: the one whose training folds did not contain it."""

    def __init__(self, path=None):
        self.map = C.read_json(path or ROUTER_DIR / "fold_map.json")

    def fold(self, key, prompt=None):
        if key not in self.map:
            raise KeyError(f"{key} is not a query of the router study's pool: no fold model is held out for it")
        fold, sha = self.map[key]
        if prompt is not None and hashlib.sha1(prompt.encode("utf-8")).hexdigest()[:16] != sha:
            raise ValueError(f"the text of {key} is not the pool's text")
        return int(fold)


class Router:
    """End-to-end router: raw query text -> (score, model choice, stage timings)."""

    def __init__(self, encoder_dir, threads=None, check=True, heads=None, fold_map=None):
        import torch
        from transformers import AutoTokenizer, BertModel
        self.torch = torch
        if threads:
            torch.set_num_threads(int(threads))
        d = Path(encoder_dir)
        if check:
            for f, want in S.ROUTER_ENCODER_FILES.items():
                if not (d / f).is_file() or C.sha256_file(d / f) != want:
                    raise C.Stop(f"router encoder file {f} is absent or not the pinned one")
        self.tok = AutoTokenizer.from_pretrained(str(d), local_files_only=True)
        self.model = BertModel.from_pretrained(str(d), add_pooling_layer=False, local_files_only=True).eval()
        self.heads = heads or Heads(check=check)
        self.folds = fold_map or FoldMap()
        self.identity = {"encoder": S.ROUTER_ENCODER, "encoder_revision": S.ROUTER_ENCODER_REVISION, "heads_sha256": self.heads.sha256,
                         "max_tokens": S.ROUTER_MAX_TOKENS, "threshold": S.ROUTER_THRESHOLD, "device": "cpu",
                         "threads": torch.get_num_threads()}

    def embed(self, text):
        torch = self.torch
        t0 = time.perf_counter()
        enc = self.tok([text], padding=True, truncation=True, max_length=S.ROUTER_MAX_TOKENS, return_tensors="pt")
        t1 = time.perf_counter()
        with torch.inference_mode():
            hidden = self.model(**enc).last_hidden_state
            mask = enc["attention_mask"].unsqueeze(-1).to(hidden.dtype)
            emb = (hidden * mask).sum(1) / mask.sum(1).clamp(min=1e-9)
            emb = torch.nn.functional.normalize(emb, p=2, dim=1)
        e = emb.numpy()
        return e, {"tokenize_s": t1 - t0, "encode_pool_s": time.perf_counter() - t1}

    def route(self, key, text):
        """Score `text` with the fold model held out for `key`. Returns the decision record."""
        t0 = time.perf_counter()
        fold = self.folds.fold(key, text)
        emb, st = self.embed(text)
        t1 = time.perf_counter()
        score = float(self.heads.score(fold, emb)[0])
        choice = choice_of(score)
        t2 = time.perf_counter()
        return {"key": key, "fold": fold, "score": score, "choice": choice, "choice_name": S.MODELS[choice]["name"],
                "router_s": t2 - t0, "tokenize_s": st["tokenize_s"], "encode_pool_s": st["encode_pool_s"], "head_s": t2 - t1}
